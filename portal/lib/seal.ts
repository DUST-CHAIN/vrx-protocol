// SALTED ATTESTED-RECORD SEAL — the privacy primitive (the design docs §3).
// SERVER-ONLY. The single implementation of the "seal a plaintext record so it's tamper-evident AND not
// reversible by a rainbow table" pattern that records consume (offers were the first; agreements and
// KYC profiles are the ones built on THIS helper).
//
// ── The hole catches ────────────────────────────────────────────────────────────────────────────
// Our attested records seal a plaintext as SHA-256(domain | salt | stableStringify(payload)). Until now
// `salt` was always "" at every call site, and `domain` ("vrx-terms", "vrx-agreement", …) is a PUBLIC
// NAMESPACE, not a secret — the code may be open-source, so an attacker knows every domain tag. For a
// LOW-ENTROPY payload (a person's name, a building name, a round price) that means the whole hash is
// precomputable: the attacker dictionary-hashes common values and matches the public on-chain digest.
// A high-entropy payload (one mixing a random id + timestamps) is already safe, but PII / names / prices
// are exactly the low-entropy case.
//
// ── The fix ──────────────────────────────────────────────────────────────────────────────────────────
// Mix a per-record SECRET random salt (a 128-bit nonce) into the hash: SHA-256(domain | random_salt |
// text). The on-chain / shared digest is now NOT precomputable — the attacker lacks the salt. The party
// holding the plaintext ALSO holds the salt (stored next to the plaintext in their private store), so they
// can still re-hash and prove the record unaltered (✓ Vetted). This is the keyed-hash / HMAC pattern the
// older Rust contract notes already gestured at (hq/hr/HMAC) — we simply start USING a real secret.
//
// ── Scope (decision) ───────────────────────────────────────────────────────────────────────
// Salt NEW record types only: KYC profiles + agreements v2. The contract stays FROZEN — we
// do NOT re-anchor the unit_keys already stamped on live testnet (their low-entropy exposure leaks only
// "a unit ref exists", never a price/identity/terms, and re-stamping would break the frozen invariant for
// a low-stakes leak). So existing offers/unit_keys keep salt="" (their digest must match what's on-chain);
// this helper is for the off-chain-only records whose seal the SERVER authors.
//
// ── Losing the salt ──────────────────────────────────────────────────────────────────────────────────
// The salt lives with the plaintext in the party-private store. Lose the salt (or the plaintext) and the
// record is no longer re-verifiable — it degrades to an opaque anchor, exactly like a record created
// outside the portal. That's acceptable and intentional: verifiability is a property of holding the data.
//
// ── The PEPPER ("low-entropy brute-force on the attested-records spine") ──────────────────
// The per-record salt defeats a rainbow table, but it is stored RIGHT NEXT TO the plaintext (same private
// store). So a single breach that leaks BOTH the .data store AND the salts still lets an attacker brute-force
// a LOW-ENTROPY payload (a phone, a plot number, a round price) against the digests. A global PEPPER closes
// that: one secret, held SEPARATELY from the per-record salts (env var now, KMS/HSM-held HMAC key later),
// mixed into every salted digest. An attacker who steals the whole .data tree but not the pepper cannot
// brute-force anything — the keying material never sits beside the plaintext.
//   • SCOPE — the pepper applies ONLY to this off-chain salted-record spine (lib/seal). The on-chain /
//     shared digest path (lib/vrx.ts hashRef, salt="") stays PEPPER-FREE on purpose: those digests must keep
//  matching what is already stamped on frozen testnet. Two paths, one unchanged (§Scope).
//   • EMPTY-SAFE — when VRX_SEAL_PEPPER is unset (dev / today) the formula is BYTE-IDENTICAL to the old
//     `${domain}|${salt}|${text}`, so nothing shifts and no migration is needed. All .data records are
//     throwaway demo seed (gitignored, regenerated by `npm run demo`); a pepper change just reseeds cleanly.
//   • STICKY — a record sealed WITH a pepper verifies ONLY with the SAME pepper (that is the whole point).
//     Rotating the pepper invalidates existing off-chain seals → acceptable here (demo seed), and in prod a
//  rotation would ride a deliberate re-seal. The empty default means verify behaves identically until
//  a pepper is deployed. LATER (KMS): swap `readPepper` to fetch an HSM/KMS-held HMAC key; call sites
//     and the format are unchanged. Future hardening is a one-function swap, not a spine change.
// KMS/HSM-held HMAC key = the fuller mitigation, flagged for its own session. This is the pepper leg.

import { createHash, randomBytes } from "crypto";

// Read ONCE at module load. A trimmed, non-empty value turns the pepper on; empty/unset = legacy behaviour.
// Held separately from any per-record salt (that is the threat-model point). Memoised so a hot path can't
// re-read process.env per hash.
let PEPPER: string | null = null;
function readPepper(): string {
  if (PEPPER === null) PEPPER = (process.env.VRX_SEAL_PEPPER ?? "").trim();
  return PEPPER;
}

/** TEST-ONLY: re-read the pepper from env (so a test can set VRX_SEAL_PEPPER then exercise seal/verify). */
export function __resetPepperForTests(): void {
  PEPPER = null;
}

/** A sealed record carries BOTH halves needed to re-verify: the secret salt + the resulting digest. */
export type Seal = {
  /** Per-record secret nonce (hex). Stored next to the plaintext; NEVER goes on-chain. */
  salt: string;
  /** SHA-256(domain | salt | stableStringify(payload)) as hex — the tamper-evident shared truth. */
  hash: string;
};

/** 128-bit random salt as hex. One per record, generated at creation, then immutable with the record. */
export function newSalt(): string {
  return randomBytes(16).toString("hex");
}

// Deterministic JSON with sorted keys — MUST match stableStringify in lib/vrx.ts / lib/offers.ts /
// lib/agreements.ts EXACTLY, so a digest is reproducible regardless of which module computes it.
function stableStringify(obj: Record<string, unknown>): string {
  const keys = Object.keys(obj).sort();
  return JSON.stringify(obj, keys);
}

/**
 * The one hashing routine. With NO pepper set the scheme is byte-identical to lib/vrx.ts hashRef
 * (`${domain}|${salt}|${text}`), so these salted records sit on the same spine as the unit_keys — only the
 * salt is no longer empty. With a pepper set, the secret is mixed in as a distinct leading segment
 * (`${pepper}|${domain}|${salt}|${text}`) so the format stays unambiguous and the pepper cannot collide with
 * a payload value. The on-chain hashRef path is deliberately NOT peppered (it must match frozen testnet).
 */
export function digest(
  payload: Record<string, unknown> | string,
  domain: string,
  salt: string
): string {
  const text = typeof payload === "string" ? payload : stableStringify(payload);
  const pepper = readPepper();
  const input = pepper ? `${pepper}|${domain}|${salt}|${text}` : `${domain}|${salt}|${text}`;
  return createHash("sha256").update(input, "utf8").digest("hex");
}

/**
 * Seal a fresh record: generate a new secret salt and compute the salted digest. Store BOTH halves of the
 * returned Seal alongside the plaintext — the salt to re-verify later, the hash as the shared seal.
 */
export function sealRecord(payload: Record<string, unknown> | string, domain: string): Seal {
  const salt = newSalt();
  return { salt, hash: digest(payload, domain, salt) };
}

/**
 * The ✓ Vetted check: re-hash the held plaintext with the record's stored salt and compare to the stored
 * hash. True = unaltered since sealing. A missing/empty salt or a mismatch returns false (a loud tamper or
 * lost-salt signal, never a silent pass).
 */
export function verifySeal(
  payload: Record<string, unknown> | string,
  domain: string,
  seal: Seal
): boolean {
  try {
    if (!seal?.salt || !seal?.hash) return false;
    return digest(payload, domain, seal.salt) === seal.hash;
  } catch {
    return false;
  }
}
