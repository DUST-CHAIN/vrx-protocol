#!/usr/bin/env node
// VRX V7-WISHLIST #6 — obfuscation moat, part 1/3: the NAME-MAP GENERATOR.
//
// WHAT: parse the contract's `#[near] impl Contract` block for every exported `pub fn`, and emit a
// DETERMINISTIC legible->opaque method-name map. This is the single source of truth consumed by
// (a) the WASM rename build-step (apply-name-map.mjs) and (b) the off-chain TS name-map module.
//
// WHY (V7_PLAN §6): make the contract "not cheaply copyable" — opaque method symbols in the DEPLOY
// WASM + on the wire, so a would-be re-hoster cannot read the method surface off the chain. The moat
// is on the SOURCE/artifact, NOT the chain's security: obscurity != the lock. Auth/crypto are
// untouched (the renamed method still runs the identical predecessor/assert logic). Source + tests
// keep the LEGIBLE names (cargo test calls by real name); only the build-for-deploy WASM is renamed.
//
// DETERMINISM: the opaque name for a method = "v" + the first 6 hex of sha256("vrxobf1|"+name).
// Stable across runs, collision-checked, prefix-"v" so it is a valid WASM export identifier and
// visibly a VRX symbol in the artifact (not an accident). A fixed domain-separator string ("vrxobf1")
// lets us rotate the scheme later (bump to vrxobf2) without colliding with a shipped map.
//
// INVARIANT: the map's DOMAIN is derived from lib.rs every run. A method added to the contract but
// not re-generated here will be caught by apply-name-map.mjs (it verifies every WASM export is
// mapped) — so a drift fails LOUDLY at build, never ships a dead method.

import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const HERE = dirname(fileURLToPath(import.meta.url));
const LIB_RS = join(HERE, "..", "src", "lib.rs");
const OUT_JSON = join(HERE, "name-map.json");

const DOMAIN = "vrxobf1"; // scheme version / domain-separator — bump to rotate the whole map

// Methods that must KEEP their legible wire name because an external tool calls them by a fixed
// name we don't control at the map layer. `new` + the migrate entrypoint are invoked by the
// cargo-near deploy/init command line; we keep them legible so the standard deploy recipe works
// unchanged. (They are owner-only lifecycle calls — their names leak nothing about the live method
// surface a copier would want. The REAL surface — register/claim/token/exclusive — is what gets
// obfuscated.) If we later drive deploy through the map too, these can fold in.
const KEEP_LEGIBLE = new Set([
  "new",
  "migrate", "migrate2", "migrate3", "migrate4", "migrate5", "migrate6", "migrate7",
]);

function exportedMethods(src) {
  // Isolate the `#[near] impl Contract { ... }` block, then collect every `pub fn <name>` in it.
  const near = src.indexOf("#[near]");
  if (near < 0) throw new Error("no #[near] attribute found in lib.rs");
  const implStart = src.indexOf("impl Contract", near);
  if (implStart < 0) throw new Error("no `impl Contract` after #[near]");
  // Brace-match from the first `{` after `impl Contract` to find the block end.
  const open = src.indexOf("{", implStart);
  let depth = 0, end = -1;
  for (let i = open; i < src.length; i++) {
    const c = src[i];
    if (c === "{") depth++;
    else if (c === "}") { depth--; if (depth === 0) { end = i; break; } }
  }
  if (end < 0) throw new Error("unbalanced braces in impl Contract block");
  const block = src.slice(open, end);
  const names = [];
  const re = /pub\s+fn\s+(\w+)/g;
  let m;
  while ((m = re.exec(block))) names.push(m[1]);
  return names;
}

function opaque(name) {
  return "v" + createHash("sha256").update(`${DOMAIN}|${name}`).digest("hex").slice(0, 6);
}

const src = readFileSync(LIB_RS, "utf8");
const methods = exportedMethods(src);
if (methods.length === 0) throw new Error("no exported methods parsed — refusing to write an empty map");

const map = {};
const seen = new Map(); // opaque -> legible, for collision detection
for (const name of methods) {
  if (KEEP_LEGIBLE.has(name)) { map[name] = name; continue; }
  const o = opaque(name);
  if (seen.has(o)) {
    throw new Error(`opaque collision: ${name} and ${seen.get(o)} both -> ${o}. Bump DOMAIN or widen the slice.`);
  }
  seen.set(o, name);
  map[name] = o;
}

const out = {
  _comment: "GENERATED by gen-name-map.mjs — do not hand-edit. Legible method name -> opaque WASM export. See obfuscation/README.md.",
  _scheme: DOMAIN,
  _count: methods.length,
  _renamed: methods.length - [...methods].filter((n) => KEEP_LEGIBLE.has(n)).length,
  map,
};
writeFileSync(OUT_JSON, JSON.stringify(out, null, 2) + "\n");

// Also emit the off-chain TS consumer so it can never drift from the JSON. The live V7 transport
// routes each `call.method` through `onchainMethod`; it's IDENTITY unless obfuscation is active
// (VRX_ONCHAIN_OBFUSCATED=1 + a deployed obfuscated wasm), so the whole off-chain codebase keeps
// using legible method names and only the single live-transport body maps at the wire boundary.
const OUT_TS = join(HERE, "..", "..", "portal", "lib", "onchain-name-map.ts");
const tsMap = Object.entries(map).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n");
const ts = `// GENERATED by contract/obfuscation/gen-name-map.mjs — DO NOT HAND-EDIT.
// VRX V7-WISHLIST #6 obfuscation moat: legible contract method name -> opaque on-wire export name.
// The DEPLOY wasm renames its exports to the opaque names (build-obfuscated.sh); NEAR dispatches by
// export symbol, so a live call must send the OPAQUE name. Source/tests/dry-run stay legible; only
// the V7 live transport maps, and only when obfuscation is active. See contract/obfuscation/README.md.
//
// scheme: ${out._scheme} · ${out._count} exports · ${out._renamed} renamed · ${KEEP_LEGIBLE.size} kept legible

export const ONCHAIN_NAME_MAP: Readonly<Record<string, string>> = Object.freeze({
${tsMap}
});

/** True when calls should carry the OPAQUE method name (an obfuscated wasm is deployed). Gated by env
 *  so dev/testnet-plain and the live obfuscated deploy share one code path. Default OFF (legible). */
export function obfuscationActive(): boolean {
  return process.env.VRX_ONCHAIN_OBFUSCATED === "1";
}

/** Map a legible contract method name to the name to send on-wire. Identity unless obfuscation is
 *  active. A name absent from the map (e.g. a view we never obfuscated) passes through unchanged.
 *  The live V7 transport MUST call this on \`call.method\` before \`functionCall\`. */
export function onchainMethod(method: string): string {
  if (!obfuscationActive()) return method;
  return ONCHAIN_NAME_MAP[method] ?? method;
}
`;
writeFileSync(OUT_TS, ts);
console.log(`name-map: ${out._count} exports, ${out._renamed} renamed, ${KEEP_LEGIBLE.size} kept legible`);
console.log(`  JSON -> ${OUT_JSON}`);
console.log(`  TS   -> ${OUT_TS}`);
